def upload_image(title, path):
    existing = WagtailImage.objects.filter(title=title).first()
    if existing:
        print(f"  [skip] {title} -> id={existing.pk}")
        return existing

    img_bytes = open(path, "rb").read()
    w, h = PILImage.open(io.BytesIO(img_bytes)).size
    filename = os.path.basename(path)

    tmp = tempfile.NamedTemporaryFile(suffix=".jpg", delete=False)
    try:
        tmp.write(img_bytes)
        tmp.flush()
        with open(tmp.name, "rb") as f:
            img = WagtailImage(title=title)
            img.file.save(filename, File(f), save=False)
        if not img.width:
            img.width = w
            img.height = h
        img.save()
    finally:
        tmp.close()
        os.unlink(tmp.name)

    print(f"  [ok] {title} -> id={img.pk}")
    return img



class Command(BaseCommand):
    help = "Удаляет страницу «Оплата и возврат» и обновляет 4 правовых документа реальным содержимым."

    def handle(self, *args, **options):
        import sys
        sys.stdout.reconfigure(encoding="utf-8")

        from tours.models import LegalPage

        # ── 1. Удалить «Оплата и возврат» ────────────────────
        payment = LegalPage.objects.filter(slug="payment-rules").first()
        if payment:
            payment.delete()
            self.stdout.write(self.style.SUCCESS("OK Удалена: Оплата и возврат"))
        else:
            self.stdout.write("Страница payment-rules не найдена (уже удалена?)")

        # ── 2. Обновить 4 страницы ────────────────────────────
        updates = [
            ("offer",                   "Публичная оферта",
             OFFER_INTRO,               OFFER_CONTENT),
            ("privacy",                 "Политика конфиденциальности",
             PRIVACY_INTRO,             PRIVACY_CONTENT),
            ("personal-data",           "Согласие на обработку персональных данных",
             PERSONAL_DATA_INTRO,       PERSONAL_DATA_CONTENT),
            ("soglasie-na-foto-video",  "Согласие на фото- и видеосъёмку",
             PHOTO_INTRO,               PHOTO_CONTENT),
        ]

        for slug, title, intro, content in updates:
            page = LegalPage.objects.filter(slug=slug).first()
            if not page:
                self.stdout.write(f"Страница не найдена: {slug}")
                continue
            page.title = title
            page.intro = intro
            page.content = content
            page.save_revision().publish()
            self.stdout.write(self.style.SUCCESS(f"OK Обновлена: {title} (/{slug}/)"))

        self.stdout.write(self.style.SUCCESS("\nГотово!"))
